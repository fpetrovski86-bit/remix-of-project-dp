const UNITS: Record<string, string> = { гр: "g" };

function capitalize(word: string) {
  return word.charAt(0).toUpperCase() + word.slice(1);
}

/** Translate a Macedonian menu string to English, word by word. */
export function translateMenuText(text: string): string {
  if (!text) return text;
  return text.replace(/[A-Za-zА-Яа-яЃѓЅѕЈјЉљЊњЌќЏџ]+/g, (word) => {
    const lower = word.toLowerCase();
    const hit = WORDS[lower] ?? UNITS[lower];
    if (!hit) return word;
    const isUpper = word === word.toUpperCase() && word.length > 1;
    if (isUpper) return hit.toUpperCase();
    const isCap = word[0] === word[0]?.toUpperCase();
    return isCap ? capitalize(hit) : hit;
  });
}

/** Pick the right text for the current language. */
export function menuText(text: string, lang: string): string {
  return lang === "en" ? translateMenuText(text) : text;
}

/** Price with the localized currency suffix. */
export function menuPrice(price: number, lang: string): string {
  return lang === "en" ? `${price} MKD` : `${price} ден`;
}
